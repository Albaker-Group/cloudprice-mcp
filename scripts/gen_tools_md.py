"""Write docs/TOOLS.md from the tool definitions the server actually exposes.

The README used to list tools by hand, and drifted: it said 25 tools, then
"10 tools appear", and its tables stopped at v0.6. Generated docs cannot
drift, and tests/test_tools_doc.py fails CI if this file is out of date.

    uv run python scripts/gen_tools_md.py
"""

from __future__ import annotations

import asyncio
from pathlib import Path

from cloudprice_mcp.server import list_tools

OUT = Path(__file__).resolve().parents[1] / "docs" / "TOOLS.md"


def render() -> str:
    tools = asyncio.run(list_tools())
    lines = [
        "# Tools",
        "",
        "<!-- Generated by scripts/gen_tools_md.py from server.py. Do not edit by hand. -->",
        "",
        f"cloudprice-mcp exposes **{len(tools)} tools**. These are the descriptions your",
        "AI assistant reads when it decides which tool to call.",
        "",
    ]
    lines += [f"- [`{t.name}`](#{t.name})" for t in tools]
    for t in tools:
        props = t.inputSchema.get("properties", {})
        required = set(t.inputSchema.get("required", []))
        lines += ["", f"## {t.name}", "", " ".join((t.description or "").split())]
        if props:
            lines += ["", "| Argument | Required |", "|---|---|"]
            lines += [f"| `{p}` | {'yes' if p in required else ''} |" for p in props]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")
